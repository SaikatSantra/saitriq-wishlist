/**
 * Deep translation lookup with parameters and fallback:
 * Requested Locale -> English -> Raw Key
 */
export function getTranslation(locale, path, params = {}) {
  const normLocale = normalizeLocale(locale);
  const keys = String(path).split(".");

  const resolve = (langObj) => {
    let curr = langObj;
    for (const k of keys) {
      if (curr && typeof curr === "object" && k in curr) {
        curr = curr[k];
      } else {
        return undefined;
      }
    }
    return curr;
  };

  let value = resolve(TRANSLATIONS[normLocale]);
  if (value === undefined && normLocale !== "en") {
    value = resolve(TRANSLATIONS.en);
  }
  if (value === undefined) {
    return path;
  }

  if (typeof value === "string") {
    return value.replace(/\{(\w+)\}/g, (_, key) => (params[key] !== undefined ? String(params[key]) : `{${key}}`));
  }

  return value;
}

/**
 * Creates a bound `t(key, params)` helper for the given locale.
 */
export function createTranslator(locale) {
  const normLocale = normalizeLocale(locale);
  const t = (key, params) => getTranslation(normLocale, key, params);
  t.locale = normLocale;
  t.raw = TRANSLATIONS[normLocale] || TRANSLATIONS.en;
  return t;
}

