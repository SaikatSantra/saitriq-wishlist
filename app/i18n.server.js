export const SUPPORTED_LOCALES = ["en", "de", "es", "fr", "it", "pt", "pt-BR"];
export const DEFAULT_LOCALE = "en";

export const normalizeLocale = (rawLocale) => {
  if (!rawLocale || typeof rawLocale !== "string") return DEFAULT_LOCALE;
  const clean = rawLocale.toLowerCase().trim().replace("_", "-");
  if (clean.startsWith("de")) return "de";
  if (clean.startsWith("es")) return "es";
  if (clean.startsWith("fr")) return "fr";
  if (clean.startsWith("it")) return "it";
  if (clean.startsWith("pt")) return "pt-BR";
  return "en";
};

export const detectLocale = ({ request, session, shopSettings }) => {
  if (request) {
    try {
      const url = new URL(request.url);
      const queryLocale = url.searchParams.get("locale");
      if (queryLocale) return normalizeLocale(queryLocale);
    } catch {}
  }
  if (session?.locale) return normalizeLocale(session.locale);
  if (shopSettings?.locale) return normalizeLocale(shopSettings.locale);
  return DEFAULT_LOCALE;
};

